import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { flattenMessages, type Messages } from '../../src/i18n/core';
import { intlLocale, locales, type Locale } from '../../src/i18n/config';

/** Mutable so tests can point the checker at a temporary copy. */
export const paths = {
  sections: path.join(process.cwd(), 'src', 'i18n', 'sections'),
  catalog: path.join(process.cwd(), 'src', 'i18n', 'catalog'),
};
const FILE_RE = /^([a-z][a-z0-9-]*)\.(en|ru|kk)\.json$/;
const PLURAL_RE = /_(zero|one|two|few|many|other)$/;

export type Tree = Record<string, unknown>;

export function listSections(): Map<string, Set<Locale>> {
  const out = new Map<string, Set<Locale>>();
  if (!existsSync(paths.sections)) return out;
  for (const name of readdirSync(paths.sections).sort()) {
    const m = FILE_RE.exec(name);
    if (!m) continue;
    const set = out.get(m[1]) ?? new Set<Locale>();
    set.add(m[2] as Locale);
    out.set(m[1], set);
  }
  return out;
}

export const sectionFile = (section: string, locale: Locale) => path.join(paths.sections, `${section}.${locale}.json`);

export function readTree(section: string, locale: Locale): Tree | null {
  const file = sectionFile(section, locale);
  if (!existsSync(file)) return null;
  return JSON.parse(readFileSync(file, 'utf8')) as Tree;
}

export function writeTree(section: string, locale: Locale, tree: Tree): void {
  writeFileSync(sectionFile(section, locale), `${JSON.stringify(tree, null, 2)}\n`, 'utf8');
}

export function flat(tree: Tree | null): Messages {
  return tree ? flattenMessages(tree) : {};
}

export function pluralCategories(locale: Locale): string[] {
  return new Intl.PluralRules(intlLocale[locale]).resolvedOptions().pluralCategories as string[];
}

/** Placeholder names used in a message, e.g. "{count} of {total, number}" → ["count", "total"]. */
export function placeholders(text: string): string[] {
  return [...text.matchAll(/\{\s*(\w+)\s*(?:,\s*\w+\s*)?\}/g)].map((m) => m[1]).sort();
}

/**
 * The keys a locale must have for a section: every plain English key, and for each English plural
 * group (`x_one`/`x_other`) every plural category of the target locale (`x_one`, `x_few`, `x_many`, `x_other` in Russian).
 * Returns key → English source text.
 */
export function expectedKeys(en: Messages, locale: Locale): Map<string, { source: string; plural?: string }> {
  const out = new Map<string, { source: string; plural?: string }>();
  const groups = new Set<string>();
  for (const key of Object.keys(en)) {
    if (PLURAL_RE.test(key)) groups.add(key.replace(PLURAL_RE, ''));
    else out.set(key, { source: en[key] });
  }
  for (const base of groups) {
    for (const cat of pluralCategories(locale)) {
      const source = en[`${base}_${cat}`] ?? en[`${base}_other`];
      if (source === undefined) continue;
      out.set(`${base}_${cat}`, { source, plural: cat });
    }
  }
  return out;
}

export function setPath(tree: Tree, key: string, value: string): void {
  const parts = key.split('.');
  let node = tree;
  for (const part of parts.slice(0, -1)) {
    if (!node[part] || typeof node[part] !== 'object') node[part] = {};
    node = node[part] as Tree;
  }
  node[parts[parts.length - 1]] = value;
}

/** Regenerates src/i18n/catalog/<locale>.ts so bundlers import every section file statically. */
export function writeCatalog(): { changed: string[] } {
  const sections = listSections();
  const changed: string[] = [];
  for (const locale of locales) {
    const present = [...sections.entries()].filter(([, set]) => set.has(locale)).map(([s]) => s);
    const ident = (s: string, i: number) => `s${i}_${s.replace(/[^a-zA-Z0-9]/g, '_')}`;
    const lines = [
      '// Generated by scripts/i18n (npm run i18n:check). Do not edit by hand.',
      ...present.map((s, i) => `import ${ident(s, i)} from '../sections/${s}.${locale}.json';`),
      '',
      'const catalog: Record<string, unknown> = {',
      ...present.map((s, i) => `  ${JSON.stringify(s)}: ${ident(s, i)},`),
      '};',
      '',
      'export default catalog;',
      '',
    ].join('\n');
    const file = path.join(paths.catalog, `${locale}.ts`);
    const before = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (before !== lines) {
      writeFileSync(file, lines, 'utf8');
      changed.push(`${locale}.ts`);
    }
  }
  return { changed };
}
